"""Verify a dataset, create its fixed split, and write statistics + a 5-sample figure.

Usage:
    python scripts/check_data.py --dataset kvasir_seg [--root PATH] [--resplit]

Outputs:
    splits/<dataset>.json                       (created once; --resplit to overwrite)
    docs/data_stats.md                          (this dataset's section is replaced)
    figures/data_<dataset>_samples.png
    <results>/summary/data_stats_<dataset>.csv  (one row per image)
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from promptshift.data import get_dataset
from promptshift.data.splits import SPLITS, make_split, save_split
from promptshift.paths import get_paths
from promptshift.prompts import box_from_mask

# Kvasir: official count (datasets.simula.no/kvasir-seg). COCO: number of sampled
# instances (spec 6.1); the official val2017 image count is checked separately.
EXPECTED_COUNT = {"kvasir_seg": 1000, "coco_val2017": 1000, "isic2018": 2594}
COCO_VAL2017_IMAGES = 5000  # https://cocodataset.org/#download (2017 Val images [5K/1GB])


def coco_instance_stats(ds, ids) -> pd.DataFrame:
    return pd.DataFrame([ds.instance_stats(i) for i in ids])


def coco_section(name, df, counts, cfg) -> str:
    c = cfg["coco"]
    cats = df["category"].value_counts()
    return "\n".join(
        [
            f"## {name}",
            "",
            "Generated by `scripts/check_data.py`; do not edit by hand.",
            "",
            f"- Images in `instances_val2017.json`: **{counts['images']}** "
            f"(official: {COCO_VAL2017_IMAGES})"
            + ("" if counts["images"] == COCO_VAL2017_IMAGES else " — **differs**"),
            f"- Annotations: {counts['annotations']} (iscrowd=1: {counts['crowd']})",
            f"- Eligible (iscrowd=0, area ≥ {c['min_area_frac']:.0%} of image): "
            f"**{counts['eligible']}**",
            f"- Sampled (seed {c['sample_seed']}): **{len(df)}** instances, all in split `test`, "
            f"from {df['image_id'].str.split('_').str[0].nunique()} distinct images",
            f"- Categories covered: {cats.size} of 80",
            f"- Instances split into ≥ 2 fragments (8-connectivity): "
            f"{int((df['n_fragments'] > 1).sum())} (kept as one object)",
            "",
            "### Top 10 categories",
            "",
            "| category | instances |",
            "|---|---|",
            *[f"| {k} | {v} |" for k, v in cats.head(10).items()],
            "",
            "### Instance area fraction",
            "",
            q(df["gt_area_frac"]),
            "",
        ]
    )


def per_image_stats(ds, ids, split_of) -> pd.DataFrame:
    rows = []
    for k, image_id in enumerate(ids, 1):
        # ISIC: statistics from masks only (images may not be downloaded)
        s = ds.mask_sample(image_id) if hasattr(ds, "mask_sample") else ds.get(image_id)
        n_px = s.mask.size
        rows.append(
            {
                "image_id": image_id,
                "split": split_of.get(image_id, ""),
                "height": s.meta["height"],
                "width": s.meta["width"],
                "n_objects": len(s.objects),
                "n_components_raw": s.meta["n_components_raw"],
                "n_specks_removed": s.meta["n_specks_removed"],
                "speck_pixels_removed": s.meta["speck_pixels_removed"],
                "gt_area_frac": float(s.mask.sum()) / n_px,
                "object_area_fracs": ";".join(f"{o.sum() / n_px:.6f}" for o in s.objects),
            }
        )
        if k % 100 == 0:
            print(f"  {k}/{len(ids)}", flush=True)
    return pd.DataFrame(rows)


def q(series, qs=(0.0, 0.05, 0.25, 0.5, 0.75, 0.95, 1.0), fmt="{:.4f}") -> str:
    vals = np.quantile(series, qs)
    head = " | ".join(f"q{int(x * 100)}" for x in qs)
    return f"| {head} |\n|{'---|' * len(qs)}\n| " + " | ".join(fmt.format(v) for v in vals) + " |"


def markdown_section(name, df, problems, expected, split, cfg, extra=()) -> str:
    n = len(df)
    obj_fracs = np.array(
        [float(x) for s in df["object_area_fracs"] if s for x in s.split(";")], dtype=float
    )
    sizes = (df["width"].astype(str) + "×" + df["height"].astype(str)).value_counts()
    obj_counts = df["n_objects"].value_counts().sort_index()
    by_split = df.groupby("split")["n_objects"].agg(["count", "sum"])
    lines = [
        f"## {name}",
        "",
        "Generated by `scripts/check_data.py`; do not edit by hand.",
        "",
        f"- Image/mask pairs found: **{n}** (official: {expected if expected else 'n/a'})"
        + ("" if expected in (None, n) else " — **count differs from the official number**"),
        f"- Images without mask: {len(problems['image_without_mask'])}; "
        f"masks without image: {len(problems['mask_without_image'])}",
        f"- Mask binarization: gray > {cfg['mask_threshold']}; speck removal: components "
        f"< {cfg['min_object_frac']} · H · W ({cfg['connectivity']}-connectivity)",
        f"- Specks removed: **{int(df['n_specks_removed'].sum())}** components "
        f"({int(df['speck_pixels_removed'].sum())} px) in "
        f"{int((df['n_specks_removed'] > 0).sum())} images",
        f"- Images with no object left after cleaning: **{int((df['n_objects'] == 0).sum())}**",
        f"- Split (seed {split['seed']}): " + ", ".join(f"{s} {len(split[s])}" for s in SPLITS),
        *extra,
        "",
        "### Objects per split",
        "",
        "| split | images | objects |",
        "|---|---|---|",
        *[
            f"| {s} | {int(by_split.loc[s, 'count'])} | {int(by_split.loc[s, 'sum'])} |"
            for s in SPLITS
            if s in by_split.index
        ],
        "",
        "### Image size (W × H)",
        "",
        f"{sizes.size} distinct sizes. Width: min {df['width'].min()}, median "
        f"{int(df['width'].median())}, max {df['width'].max()}. Height: min {df['height'].min()}, "
        f"median {int(df['height'].median())}, max {df['height'].max()}.",
        "",
        "| size | images |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in sizes.head(10).items()],
        *(
            [f"| other ({sizes.size - 10} sizes) | {int(sizes.iloc[10:].sum())} |"]
            if sizes.size > 10
            else []
        ),
        "",
        "### Objects per image",
        "",
        "| objects | images |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in obj_counts.items()],
        "",
        "### Object area fraction (per object)",
        "",
        q(obj_fracs),
        "",
        "### GT area fraction (per image)",
        "",
        q(df["gt_area_frac"]),
        "",
    ]
    return "\n".join(lines)


def replace_section(md_path: Path, name: str, body: str) -> None:
    begin, end = f"<!-- BEGIN {name} -->", f"<!-- END {name} -->"
    block = f"{begin}\n{body}\n{end}"
    header = (
        "# Data statistics\n\nOne section per dataset, each generated by `scripts/check_data.py`.\n"
    )
    text = md_path.read_text(encoding="utf-8") if md_path.exists() else header
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    text = (
        pattern.sub(lambda _: block, text)
        if pattern.search(text)
        else text.rstrip() + "\n\n" + block + "\n"
    )
    md_path.write_text(text, encoding="utf-8")


def plot_samples(ds, ids, out: Path, seed: int) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    chosen = [
        ids[i] for i in sorted(np.random.default_rng(seed).choice(len(ids), 5, replace=False))
    ]
    fig, axes = plt.subplots(2, 5, figsize=(16, 6.4))
    for j, image_id in enumerate(chosen):
        if hasattr(ds, "ensure_image"):
            ds.ensure_image(image_id)  # COCO locally: fetch only the 5 sample images
        s = ds.get(image_id)
        axes[0, j].imshow(s.image)
        axes[0, j].set_title(f"{image_id[:12]}… {s.image.shape[1]}×{s.image.shape[0]}", fontsize=8)
        axes[1, j].imshow(s.image)
        axes[1, j].imshow(np.ma.masked_where(~s.mask, s.mask), cmap="autumn", alpha=0.45)
        for obj in s.objects:
            x0, y0, x1, y1 = box_from_mask(obj)
            axes[1, j].add_patch(
                plt.Rectangle((x0, y0), x1 - x0, y1 - y0, fill=False, ec="#00e5ff", lw=1.5)
            )
        axes[1, j].set_title(f"GT mask + boxes ({len(s.objects)} obj)", fontsize=8)
    for ax in axes.ravel():
        ax.set_xticks([])
        ax.set_yticks([])
    fig.suptitle(f"{ds.name}: 5 random samples (seed {seed})", fontsize=10)
    fig.tight_layout()
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=120)
    plt.close(fig)


def main() -> int:
    paths = get_paths()
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument("--dataset", required=True)
    parser.add_argument("--config", type=Path, default=paths.configs / "default.yaml")
    parser.add_argument("--root", type=Path, default=None, help="storage root (default: paths.py)")
    parser.add_argument("--resplit", action="store_true", help="overwrite an existing split file")
    args = parser.parse_args()
    paths = get_paths(args.root)
    cfg = yaml.safe_load(args.config.read_text(encoding="utf-8"))
    data_cfg, split_cfg = cfg["data"], cfg["data"]["split"]

    split_file = paths.splits / f"{args.dataset}.json"
    ds = get_dataset(args.dataset, paths.data, data_cfg)
    ids = ds.all_ids()
    expected = EXPECTED_COUNT.get(args.dataset)
    print(f"{args.dataset}: {len(ids)} pairs (official {expected})")
    for k, v in ds.problems.items():
        if v:
            print(f"  WARNING {k}: {len(v)} e.g. {v[:3]}")

    extra_lines, extra_ok = ds.count_check() if hasattr(ds, "count_check") else ([], True)
    for line in extra_lines:
        print(" ", line)

    if split_file.exists() and not args.resplit:
        print(f"using existing split {split_file}")
    elif hasattr(ds, "make_split"):  # dataset-specific (COCO: sampled instances, test only)
        split = ds.make_split()
        c = data_cfg["coco"]
        save_split(split_file, args.dataset, split, c["sample_seed"], {"test": 1.0})
        print(f"wrote {split_file}")
    else:
        split = make_split(ids, split_cfg["fractions"], split_cfg["seed"])
        save_split(split_file, args.dataset, split, split_cfg["seed"], split_cfg["fractions"])
        print(f"wrote {split_file}")
    ds = get_dataset(args.dataset, paths.data, data_cfg, split_file)
    split = {s: ds.ids(s) for s in SPLITS}
    split["seed"] = split_cfg["seed"]
    split_of = {i: s for s in SPLITS for i in split[s]}

    print("computing per-image statistics")
    is_coco = hasattr(ds, "instance_stats")
    df = coco_instance_stats(ds, ds.all_ids()) if is_coco else per_image_stats(ds, ids, split_of)
    paths.summary_results.mkdir(parents=True, exist_ok=True)
    csv_path = paths.summary_results / f"data_stats_{args.dataset}.csv"
    df.to_csv(csv_path, index=False)
    print(f"wrote {csv_path}")

    md_path = paths.docs / "data_stats.md"
    if is_coco:
        counts = ds.counts()
        print(f"  {counts}")
        body = coco_section(args.dataset, df, counts, data_cfg)
    else:
        body = markdown_section(
            args.dataset, df, ds.problems, expected, split, data_cfg, extra_lines
        )
    replace_section(md_path, args.dataset, body)
    print(f"updated {md_path}")

    fig_path = paths.figures / f"data_{args.dataset}_samples.png"
    plot_samples(ds, split["test"], fig_path, seed=cfg["global_seed"])
    print(f"wrote {fig_path}")

    ok = (expected is None or len(ids) == expected) and not any(ds.problems.values())
    ok = ok and extra_ok
    print("CHECK", "OK" if ok else "MISMATCH (see docs/data_stats.md)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
