def notebook(cells: list[dict]) -> dict:
    out = []
    for i, c in enumerate(cells):
        src = c["source"].rstrip("\n").split("\n")
        c = {**c, "id": f"cell-{i:02d}", "source": [s + "\n" for s in src[:-1]] + src[-1:]}
        out.append(c)
    return {
        "cells": out,
        "metadata": {
            "accelerator": "GPU",
            "colab": {"gpuType": "T4", "provenance": []},
            "kernelspec": {"display_name": "Python 3", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def render(name: str) -> str:
    return json.dumps(notebook(NOTEBOOKS[name]), indent=1, ensure_ascii=False) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if notebooks are stale")
    args = parser.parse_args()
    NB_DIR.mkdir(exist_ok=True)
    stale = []
    for name in NOTEBOOKS:
        path = NB_DIR / f"{name}.ipynb"
        text = render(name)
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.name)
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
                print(f"wrote {path}")
    if args.check and stale:
        print(f"stale notebooks: {stale}; run python scripts/build_notebooks.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
